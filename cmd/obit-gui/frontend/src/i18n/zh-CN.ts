const digits = "〇一二三四五六七八九";
// 报纸和账簿式的中文数字：四、十六、二十六。
export function cn(n: number): string {
  if (n < 0 || n > 99) return String(n);
  if (n < 10) return digits[n];
  const t = Math.floor(n / 10);
  const o = n % 10;
  return `${t > 1 ? digits[t] : ""}十${o ? digits[o] : ""}`;
}
