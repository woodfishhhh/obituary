func TestVersionInfo(t *testing.T) {
	for _, tc := range []struct {
		release string
		fixed   [4]uint16
	}{
		{"0.0.0-dev", [4]uint16{}},
		{"1.2.3", [4]uint16{1, 2, 3, 0}},
		{"4.5.6-SNAPSHOT-a1b2c3", [4]uint16{4, 5, 6, 0}},
		{"65535.2.3+build.7", [4]uint16{65535, 2, 3, 0}},
	} {
		t.Run(tc.release, func(t *testing.T) {
			for _, app := range applications {
				vi, err := versionInfo("../..", app, tc.release)
				if err != nil {
					t.Fatal(err)
				}
				decoded, err := version.FromBytes(vi.Bytes())
				if err != nil {
					t.Fatal(err)
				}
				if decoded.FileVersion != tc.fixed || decoded.ProductVersion != tc.fixed {
					t.Fatalf("fixed version: file=%v product=%v", decoded.FileVersion, decoded.ProductVersion)
				}
				for key, want := range map[string]string{
					"ProductName": "Obituary 讣告", "FileDescription": app.description,
					"CompanyName": "woodfishhhh", "LegalCopyright": "Copyright (c) 2026 woodfishhhh",
					"FileVersion": tc.release, "ProductVersion": tc.release, "OriginalFilename": app.name + ".exe",
				} {
					if got := decoded.Table().GetMainTranslation()[key]; got != want {
						t.Errorf("%s = %q, want %q", key, got, want)
					}
				}
			}
		})
	}
	for _, invalid := range []string{"", "1.2", "65536.0.0", "1.2.3\x00"} {
		if _, err := versionInfo("../..", applications[0], invalid); err == nil {
			t.Errorf("accepted invalid version %q", invalid)
		}
	}
}

func TestResourceObjectsAreReproducible(t *testing.T) {
	icon, err := brandIcon("../..")
	if err != nil {
		t.Fatal(err)
	}
	for _, app := range applications {
		for _, arch := range app.arches {
			var outputs [2]bytes.Buffer
			for i := range outputs {
				rs, err := resources("../..", app, "1.2.3-SNAPSHOT-abc123", icon)
				if err != nil {
					t.Fatal(err)
				}
				if err := rs.WriteObject(&outputs[i], arch); err != nil {
					t.Fatal(err)
				}
			}
			if !bytes.Equal(outputs[0].Bytes(), outputs[1].Bytes()) {
				t.Fatalf("%s/%s resource object is not reproducible", app.name, arch)
			}
			object, err := pe.NewFile(bytes.NewReader(outputs[0].Bytes()))
			if err != nil {
				t.Fatal(err)
			}
			if object.TimeDateStamp != 0 || object.Section(".rsrc") == nil {
				t.Fatalf("%s/%s: resource section missing or timestamp-dependent", app.name, arch)
			}
		}
	}
}

func TestApplicationManifest(t *testing.T) {
	parsed, err := winres.AppManifestFromXML(manifest)
	if err != nil {
		t.Fatal(err)
	}
	if parsed.DPIAwareness != winres.DPIPerMonitorV2 || !parsed.LongPathAware || parsed.UIAccess || parsed.ExecutionLevel != winres.AsInvoker {
		t.Fatalf("DPI/path/privilege manifest settings: %+v", parsed)
	}
	var settings struct {
		CodePage string `xml:"application>windowsSettings>activeCodePage"`
	}
	if err := xml.Unmarshal(manifest, &settings); err != nil {
		t.Fatal(err)
	}
	if settings.CodePage != "UTF-8" {
		t.Fatalf("activeCodePage = %q", settings.CodePage)
	}
}

func TestWindowsSelectsExactIconSizes(t *testing.T) {
	icon, err := brandIcon("../..")
	if err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	if err := icon.SaveICO(&generated); err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile("../../internal/tray/obituary.ico")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(committed, generated.Bytes()) {
		t.Fatal("tray ICO is stale; run go generate ./cmd/obit")
	}
	rs, err := resources("../..", applications[1], "0.0.0-dev", icon)
	if err != nil {
		t.Fatal(err)
	}
	group := rs.Get(winres.RT_GROUP_ICON, appIconID, winres.LCIDNeutral)
	if !bytes.Equal(rs.Get(winres.RT_GROUP_ICON, classIconID, winres.LCIDNeutral), group) {
		t.Fatal("the taskbar's class icon (IDI_APPLICATION) must be the application icon")
	}
	lookup := windows.NewLazySystemDLL("user32.dll").NewProc("LookupIconIdFromDirectoryEx")
	// Match Windows' small (16px) and systray LR_DEFAULTSIZE (32px) metrics
	// at 100%, 150%, and 200%, without changing the user's display settings.
	for _, size := range []uintptr{16, 24, 32, 32, 48, 64} {
		id, _, callErr := lookup.Call(uintptr(unsafe.Pointer(&group[0])), 1, size, size, 0)
		if id == 0 {
			t.Fatal(callErr)
		}
		frame, err := png.DecodeConfig(bytes.NewReader(rs.Get(winres.RT_ICON, winres.ID(id), winres.LCIDNeutral)))
		if err != nil {
			t.Fatal(err)
		}
		if frame.Width != int(size) || frame.Height != int(size) {
			t.Fatalf("Windows selected %dx%d for %dpx", frame.Width, frame.Height, size)
		}
	}
}
