type menuFiles struct{}

func UserRegistry() Registry {
	if Current != nil {
		return Current
	}
	return menuFiles{}
}
func (menuFiles) Lock() (func(), error) {
	home, err := userdirs.Data()
	if err != nil {
		return nil, err
	}
	if err = os.MkdirAll(home, 0700); err != nil {
		return nil, err
	}
	return core.LockFile(filepath.Join(home, "menu.lock"), true)
}
func (menuFiles) ReadTree(path string) (Tree, error) {
	st, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	if !st.Mode().IsRegular() {
		return nil, fmt.Errorf("preserved non-regular menu file %s", path)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return Tree{"": {"data": string(data), "mode": fmt.Sprintf("%o", st.Mode().Perm())}}, nil
}
func menuFile(data string, mode os.FileMode) Tree {
	return Tree{"": {"data": stamped(data, mode), "mode": fmt.Sprintf("%o", mode)}}
}

// A self-checking comment identifies generated bytes after the binary moves. User edits invalidate it.
func stamped(data string, mode os.FileMode) string {
	marker := fmt.Sprintf("obituary-menu-v1 %x", sha256.Sum256([]byte(fmt.Sprintf("%o:%s", mode, data))))
	if strings.HasPrefix(data, "<?xml") {
		return data + "\n<!-- " + marker + " -->\n"
	}
	return data + "\n# " + marker + "\n"
}
func ownedFile(t Tree) bool {
	if t == nil {
		return false
	}
	data := t[""]["data"]
	sep := "\n# obituary-menu-v1 "
	if strings.HasPrefix(data, "<?xml") {
		sep = "\n<!-- obituary-menu-v1 "
	}
	i := strings.LastIndex(data, sep)
	mode := os.FileMode(0600)
	if t[""]["mode"] == "700" {
		mode = 0700
	} else if t[""]["mode"] != "600" {
		return false
	}
	return i >= 0 && stamped(data[:i], mode) == data
}
func (r menuFiles) CompareAndSwap(c Change) error {
	before, err := r.ReadTree(c.Path)
	if err != nil {
		return err
	}
	if !reflect.DeepEqual(before, c.Before) {
		return fmt.Errorf("preserved changed file %s", c.Path)
	}
	if c.After == nil {
		return os.Remove(c.Path)
	}
	parent := filepath.Dir(c.Path)
	if err = os.MkdirAll(parent, 0700); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(parent, ".obituary-menu-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	mode := os.FileMode(0600)
	if c.After[""]["mode"] == "700" {
		mode = 0700
	}
	if err = tmp.Chmod(mode); err == nil {
		_, err = tmp.WriteString(c.After[""]["data"])
	}
	err = errors.Join(err, tmp.Close())
	if err != nil {
		return err
	}
	if c.Before == nil {
		return os.Link(tmp.Name(), c.Path)
	}
	return os.Rename(tmp.Name(), c.Path)
}
func Plan(reg Registry, exe string, remove bool) ([]Change, error) {
	return PlanLanguage(reg, exe, remove, config.UILanguage())
}
func Apply(reg Registry, c []Change) error {
	if len(c) == 0 {
		return nil
	}
	_, err := ApplyWithReceipt(reg, c)
	return err
}
func Inspect(reg Registry, exe string) (Status, error) {
	return InspectLanguage(reg, exe, config.UILanguage())
}
func InspectLanguage(reg Registry, exe string, lang i18n.Language) (Status, error) {
	want, err := nativeMenus(exe, lang)
	if err != nil {
		return Status{}, err
	}
	var s Status
	matches := 0
	for path, expected := range want {
		before, err := reg.ReadTree(path)
		if err != nil {
			return s, err
		}
		s.Installed = s.Installed || before != nil
		if reflect.DeepEqual(before, expected) {
			matches++
		}
	}
	s.Current = matches == len(want)
	s.Detail = fmt.Sprintf("%d/%d", matches, len(want))
	if !s.Installed {
		other := i18n.English
		if lang == other {
			other = i18n.Chinese
		}
		old, err := nativeMenus(exe, other)
		if err != nil {
			return s, err
		}
		for path := range old {
			v, err := reg.ReadTree(path)
			if err != nil {
				return s, err
			}
			s.Installed = s.Installed || v != nil
		}
	}
	return s, nil
}
func PlanLanguage(reg Registry, exe string, remove bool, lang i18n.Language) ([]Change, error) {
	if !filepath.IsAbs(exe) || strings.ContainsAny(exe, "\x00\r\n") {
		return nil, errors.New("menu requires an absolute, single-line executable path")
	}
	want, err := nativeMenus(exe, lang)
	if err != nil {
		return nil, err
	}
	other := i18n.English
	if lang == other {
		other = i18n.Chinese
	}
	alt, err := nativeMenus(exe, other)
	if err != nil {
		return nil, err
	}
	all := maps.Clone(alt)
	maps.Copy(all, want)
	var changes []Change
	for _, path := range slices.Sorted(maps.Keys(all)) {
		before, err := reg.ReadTree(path)
		if err != nil {
			return nil, err
		}
		after := want[path]
		if remove {
			after = nil
		}
		if reflect.DeepEqual(before, after) {
			continue
		}
		if before != nil && !ownedFile(before) {
			if remove || after == nil {
				continue
			}
			return nil, fmt.Errorf("preserved modified menu: %s", path)
		}
		changes = append(changes, Change{path, before, after})
	}
	return changes, nil
}

type menuAction struct {
	id  string
	key i18n.Key
}

var menuActions = []menuAction{{"1d", i18n.OneDay}, {"7d", i18n.SevenDays}, {"30d", i18n.ThirtyDays}, {"bury", i18n.BuryNow}, {"resurrect", i18n.ResurrectLatest}, {"policy", i18n.FolderPolicy}}

func (a menuAction) label(lang i18n.Language) string {
	if strings.HasSuffix(a.id, "d") {
		return lang.Text(i18n.Mark) + " · " + lang.Text(a.key)
	}
	return lang.Text(a.key)
}
func (a menuAction) command(exe, selection string) string {
	switch a.id {
	case "1d", "7d", "30d":
		return exe + " mark -- " + selection + " " + a.id
	case "bury":
		return exe + " bury -- " + selection
	default:
		return exe + " context-menu " + a.id + " -- " + selection
	}
}
func shellQuote(s string) string {
	q := string(rune(39))
	return q + strings.ReplaceAll(s, q, q+"\\"+q+q) + q
}
