// Generated by scripts/winres from docs/assets/brand/obituary-mark-512.png.
// fyne.io/systray loads it with LoadImageW/LR_DEFAULTSIZE: Windows selects
// 32/48/64px at 100/150/200% scaling; 16/24/32px layers cover small icons too.
//
//go:embed obituary.ico
var icon []byte

type menu struct {
	resident                        *app.Resident
	gui                             menuItem
	update                          menuItem
	openGUI                         guiAction
	status, recent, upcoming, pause menuItem
	open, quit                      menuItem
	rows                            []menuItem
	ui                              menuUI
	language                        i18n.Language
	loadLanguage                    func() i18n.Language
	rowCancel                       context.CancelFunc
	actions                         chan func() error
}

// Run keeps the native loop on the main thread to meet its threading contract;
// menu callbacks and the background service use Go goroutines.
func Run(svc *core.Service, logger *log.Logger) error {
	r, err := app.NewResident(svc, logger)
	if err != nil || r == nil {
		return err
	}
	defer r.Close()
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	changed := make(chan struct{}, 1)
	r.Changed = func() {
		select {
		case changed <- struct{}{}:
		default:
		}
	}
	done := make(chan error, 1)
	systray.Run(func() {
		m := newMenu(r)
		go followVisibility(ctx, logger)
		go func() { done <- r.Run(ctx); systray.Quit() }()
		go m.run(ctx, cancel, changed, logger)
	}, cancel)
	cancel()
	return <-done
}

func newMenu(r *app.Resident) *menu {
	systray.SetIcon(icon)
	exe, err := os.Executable()
	gui := newGUIAction(exe, startGUI)
	if err != nil {
		gui.enabled, gui.detail = false, err.Error()
	}
	return makeMenu(r, gui, menuUI{
		addItem:      func(title, tooltip string) menuItem { return nativeItem{systray.AddMenuItem(title, tooltip)} },
		addSeparator: systray.AddSeparator,
		tooltip:      systray.SetTooltip,
		notify:       showBalloon,
	}, config.UILanguage)
}

func (m *menu) run(ctx context.Context, cancel context.CancelFunc, changed <-chan struct{}, logger *log.Logger) {
	m.refresh(ctx)
	defer m.rowCancel()
	for {
		var err error
		select {
		case <-ctx.Done():
			return
		case <-m.quit.clicks():
			cancel()
			return
		case <-m.open.clicks():
			err = openDirectory(m.resident.Service.Store.Home)
		case <-m.gui.clicks():
			err = m.openGUI.open()
		case <-m.update.clicks():
			err = m.openGUI.open()
		case <-m.pause.clicks():
			err = m.togglePause()
		case action := <-m.actions:
			err = action()
			m.refresh(ctx)
		case <-changed:
			m.refresh(ctx)
		}
		if err != nil {
			text := fmt.Sprintf(m.language.Text(i18n.Incomplete), err)
			m.status.SetTitle(label(text))
			logger.Printf("tray: %v", err)
			m.tell(text)
		}
	}
}

func (m *menu) togglePause() error {
	home := m.resident.Service.Store.Home
	paused, err := app.Paused(home)
	if err != nil {
		return err
	}
	return app.SetPaused(home, !paused)
}

func (m *menu) refresh(ctx context.Context) {
	m.localize()
	m.refreshUpdate()
	if m.rowCancel != nil {
		m.rowCancel()
	}
	for _, row := range m.rows {
		row.Remove()
	}
	m.rows = nil
	ctx, m.rowCancel = context.WithCancel(ctx)
	if err := m.recentRows(ctx); err != nil {
		m.status.SetTitle(label(fmt.Sprintf(m.language.Text(i18n.ReadGravesFailed), err)))
	}
	if err := m.upcomingRows(ctx); err != nil {
		m.status.SetTitle(label(fmt.Sprintf(m.language.Text(i18n.ReadUpcomingFailed), err)))
	}
	paused, err := app.Paused(m.resident.Service.Store.Home)
	if err != nil {
		m.status.SetTitle(label(err.Error()))
		return
	}
	m.showPaused(paused)
}

func (m *menu) refreshUpdate() {
	state, err := update.Read(m.resident.Service.Store.Home)
	if err != nil || !update.Newer(buildinfo.Version, state.Latest.Version) {
		m.update.Hide()
		return
	}
	m.update.SetTitle(fmt.Sprintf(m.language.Text(i18n.UpdateAvailable), state.Latest.Version))
	m.update.SetTooltip(m.openGUI.tooltip)
	m.update.Show()
}

func (m *menu) recentRows(ctx context.Context) error {
	rows, err := m.resident.RecentBurials()
	if err != nil {
		return err
	}
	if len(rows) == 0 {
		m.addInfo(m.recent, m.language.Text(i18n.NoGraves))
	}
	now := time.Now()
	for _, burial := range rows {
		row := m.recent.AddSubMenuItem(label(rowTitle(m.language, burial.Path, burial.BuriedAt, now)), burial.Path)
		m.rows = append(m.rows, row)
		id := burial.ID
		go m.listen(ctx, row, func() error {
			result, err := m.resident.Restore(id)
			if result.Action == core.ActionResurrected {
				text := fmt.Sprintf(m.language.Text(i18n.Restored), result.Path, result.Warning)
				m.status.SetTitle(label(text))
				m.tell(text)
			}
			return err
		})
	}
	return nil
}

// tell shows a click's outcome after the menu has closed. It is best effort:
// the status row keeps the text for the next time the menu opens.
func (m *menu) tell(text string) {
	_ = m.ui.notify(m.language.Text(i18n.AppName), text)
}

// listen hands a row's clicks to the menu loop until the rows are rebuilt.
func (m *menu) listen(ctx context.Context, row menuItem, action func() error) {
	for {
		select {
		case <-ctx.Done():
			return
		case <-row.clicks():
			select {
			case <-ctx.Done():
				return
			case m.actions <- action:
			}
		}
	}
}

func (m *menu) upcomingRows(ctx context.Context) error {
	now := time.Now()
	rows, err := m.resident.Upcoming(now)
	if err != nil {
		return err
	}
	if len(rows) == 0 {
		m.addInfo(m.upcoming, m.language.Text(i18n.NoUpcoming))
	}
	for _, item := range rows {
		// A row opens the window, where it can be extended or spared.
		row := m.upcoming.AddSubMenuItem(label(rowTitle(m.language, item.Path, item.ExpiresAt, now)), item.Path)
		m.rows = append(m.rows, row)
		if !m.openGUI.enabled {
			row.Disable()
			continue
		}
		go m.listen(ctx, row, m.openGUI.open)
	}
	return nil
}

// rowTitle reads as a day and time, the name, then the folder it is in.
func rowTitle(language i18n.Language, path string, at, now time.Time) string {
	title := dayTime(language, at.Local(), now.Local()) + "   " + filepath.Base(path)
	if dir := filepath.Dir(path); dir != "." && dir != path {
		title += "  ·  " + filepath.Base(dir)
	}
	return title
}

func dayTime(language i18n.Language, at, now time.Time) string {
	clock := at.Format("15:04")
	day := func(t time.Time) time.Time { y, m, d := t.Date(); return time.Date(y, m, d, 0, 0, 0, 0, t.Location()) }
	// Rounding keeps a 23- or 25-hour daylight-saving day a whole day.
	switch day(at).Sub(day(now)).Round(24*time.Hour) / (24 * time.Hour) {
	case -1:
		return fmt.Sprintf(language.Text(i18n.YesterdayAt), clock)
	case 0:
		return fmt.Sprintf(language.Text(i18n.TodayAt), clock)
	case 1:
		return fmt.Sprintf(language.Text(i18n.TomorrowAt), clock)
	}
	return at.Format("01-02 15:04")
}

func (m *menu) addInfo(parent menuItem, title string) {
	row := parent.AddSubMenuItem(label(title), "")
	row.Disable()
	m.rows = append(m.rows, row)
}

func label(value string) string {
	return strings.NewReplacer("&", "&&", "\r", " ", "\n", " ", "\t", " ").Replace(value)
}

func openDirectory(path string) error {
	cmd, err := directoryCommand(path)
	if err != nil {
		return err
	}
	if err := cmd.Start(); err != nil {
		return err
	}
	return cmd.Process.Release()
}

func directoryCommand(path string) (*exec.Cmd, error) {
	windowsDir, err := windows.GetWindowsDirectory()
	if err != nil {
		return nil, err
	}
	return exec.Command(filepath.Join(windowsDir, "explorer.exe"), path), nil
}
